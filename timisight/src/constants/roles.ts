// The three kinds of account. The database owns the truth (user_roles_a0, see
// web/supabase/roles-commissions.sql); the app only reads it and shows the matching UI.
//   user         visitor: collects flowers, earns points, uses the shop
//   organization commissions statues from artists
//   artist       is listed in the artist directory and answers commission requests
export type Role = 'user' | 'organization' | 'artist';

export const ROLES: Role[] = ['user', 'organization', 'artist'];

// How each role looks, so you can tell at a glance which kind of account you are in:
// the pill under your name, and the highlight colour of the selected tab.
